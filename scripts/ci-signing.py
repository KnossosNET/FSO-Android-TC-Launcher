"""Configure stable release signing from GitHub Actions secrets without printing them."""
import argparse
import base64
import binascii
import os
from pathlib import Path

SECRET_NAMES = ("ANDROID_KEYSTORE_BASE64", "ANDROID_KEYSTORE_PASSWORD", "ANDROID_KEY_ALIAS", "ANDROID_KEY_PASSWORD")
MARKER = "# Generated by scripts/ci-signing.py\n"


def property_value(value):
    escaped = []
    special = {"\\": "\\\\", "\n": "\\n", "\r": "\\r", "\t": "\\t", "\f": "\\f", " ": "\\ "}
    for char in value:
        if char in special:
            escaped.append(special[char])
        elif ord(char) < 32 or ord(char) > 126:
            encoded = char.encode("utf-16-be")
            escaped.extend("\\u" + encoded[i:i + 2].hex() for i in range(0, len(encoded), 2))
        else:
            escaped.append(char)
    return "".join(escaped)


def prepare(root, environment):
    missing = [name for name in SECRET_NAMES if not environment.get(name)]
    if missing:
        raise ValueError("Configure GitHub repository secrets: " + ", ".join(missing))
    try:
        key = base64.b64decode("".join(environment["ANDROID_KEYSTORE_BASE64"].split()), validate=True)
    except (ValueError, binascii.Error):
        raise ValueError("ANDROID_KEYSTORE_BASE64 is not valid base64") from None
    if not key:
        raise ValueError("The signing keystore is empty")
    root = root.resolve()
    config = root / "signing.properties"
    keystore = root / "signing/ci-release.jks"
    if config.exists() or keystore.exists():
        raise ValueError("Existing signing files will not be replaced")
    keystore.parent.mkdir(parents=True, exist_ok=True)
    keystore.write_bytes(key)
    values = {
        "storeFile": "signing/ci-release.jks",
        "storePassword": environment["ANDROID_KEYSTORE_PASSWORD"],
        "keyAlias": environment["ANDROID_KEY_ALIAS"],
        "keyPassword": environment["ANDROID_KEY_PASSWORD"],
    }
    try:
        keystore.chmod(0o600)
        config.write_text(MARKER + "".join(name + "=" + property_value(value) + "\n"
                                          for name, value in values.items()), "ascii")
        config.chmod(0o600)
    except OSError:
        keystore.unlink(missing_ok=True)
        if config.exists() and config.read_text("ascii").startswith(MARKER):
            config.unlink()
        raise


def clean(root):
    config = root / "signing.properties"
    if config.exists() and config.read_text("ascii").startswith(MARKER):
        config.unlink()
        (root / "signing/ci-release.jks").unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clean", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    try:
        if args.clean:
            clean(root)
        else:
            prepare(root, os.environ)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Signing setup failed: {error}\n")


if __name__ == "__main__":
    main()
